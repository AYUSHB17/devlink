#[allow(dead_code)]
pub const HID_NUMLOCK: u16 = 0x53;
#[allow(dead_code)]
pub const HID_PAUSE: u16 = 0x48;

#[allow(dead_code)]
pub fn mac_from_hid(hid: u16) -> Option<u16> {
    TABLE.iter().find(|r| r.0 == hid).map(|r| r.1).filter(|&m| m != NONE_MAC)
}
#[allow(dead_code)]
pub fn hid_from_mac(mac: u16) -> Option<u16> {
    TABLE.iter().find(|r| r.1 == mac).map(|r| r.0)
}
#[allow(dead_code)]
pub fn win_from_hid(hid: u16) -> Option<u16> {
    TABLE.iter().find(|r| r.0 == hid).map(|r| r.2).filter(|&w| w != 0)
}
#[allow(dead_code)]
pub fn hid_from_win(scan: u16) -> Option<u16> {
    if scan == 0 {
        return None;
    }
    TABLE.iter().find(|r| r.2 == scan).map(|r| r.0)
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn round_trips() {
        assert_eq!(mac_from_hid(0x04), Some(0x00)); // a
        assert_eq!(hid_from_mac(0x37), Some(0xe3)); // Cmd -> left GUI
        assert_eq!(win_from_hid(0xe3), Some(0xe05b)); // left Win
        assert_eq!(hid_from_win(0xe048), Some(0x52)); // Up
        assert_eq!(hid_from_mac(0x69), Some(0x68)); // Mac F13 stays F13
        assert_eq!(win_from_hid(0x46), Some(0xe037)); // PrintScreen
        // every HID row with both codes maps back to itself or an earlier alias
        for &(hid, mac, win) in TABLE {
            if mac != NONE_MAC {
                assert!(hid_from_mac(mac).is_some(), "mac {mac:#x}");
            }
            if win != 0 {
                assert!(hid_from_win(win).is_some(), "win {win:#x} for hid {hid:#x}");
            }
        }
    }
}
